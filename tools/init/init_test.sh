#!/usr/bin/env bash

set -o errexit -o nounset -o pipefail

# --- begin runfiles.bash initialization v3 ---
# Copy-pasted from the Bazel Bash runfiles library v3.
set -uo pipefail
set +e
f=bazel_tools/tools/bash/runfiles/runfiles.bash
# shellcheck disable=SC1090
source "${RUNFILES_DIR:-/dev/null}/$f" 2>/dev/null \
  || source "$(grep -sm1 "^$f " "${RUNFILES_MANIFEST_FILE:-/dev/null}" | cut -f2- -d' ')" 2>/dev/null \
  || source "$0.runfiles/$f" 2>/dev/null \
  || source "$(grep -sm1 "^$f " "$0.runfiles_manifest" | cut -f2- -d' ')" 2>/dev/null \
  || source "$(grep -sm1 "^$f " "$0.exe.runfiles_manifest" | cut -f2- -d' ')" 2>/dev/null \
  || {
    echo >&2 "ERROR: cannot find $f"
    exit 1
  }
f=
set -e
# --- end runfiles.bash initialization v3 ---

init_sh="$(rlocation "rules_swift_package_manager/tools/init/init.sh")"
fixtures="rules_swift_package_manager/tools/swift_deps_tool/Tests/fixtures"
fixture="$(rlocation "${fixtures}/inc.MODULE.bazel.empty.expected")"

fail() {
  echo >&2 "FAIL: ${*}"
  exit 1
}

assert_file() {
  [[ -f ${1} ]] || fail "expected file ${1}"
}

assert_count() {
  local expected="${1}" line="${2}" file="${3}"
  local actual
  actual="$(grep -cxF -- "${line}" "${file}" || true)"
  [[ ${actual} -eq ${expected} ]] \
    || fail "expected ${expected} x '${line}' in ${file}, got ${actual}"
}

ws="$(mktemp -d)"
trap 'rm -rf "${ws}"' EXIT
export BUILD_WORKSPACE_DIRECTORY="${ws}"
mkdir -p "${ws}/swift"
echo "// swift-tools-version: 5.9" >"${ws}/swift/Package.swift"
echo '{"pins":[]}' >"${ws}/seed.resolved"
printf 'existing' >"${ws}/.gitignore"
echo 'module(name = "client")' >"${ws}/MODULE.bazel"

# First init, with a seed.
out="$("${init_sh}" --config @platforms//os:macos \
  --swift swift/Package.swift --dir swift/macos --seed seed.resolved)"

assert_file "${ws}/swift/macos/BUILD.bazel"
assert_file "${ws}/swift/macos/inc.MODULE.bazel"
assert_file "${ws}/swift/macos/Package.resolved"
assert_file "${ws}/seed.resolved"

cmp "${fixture}" "${ws}/swift/macos/inc.MODULE.bazel" \
  || fail "inc.MODULE.bazel differs from the fixture"
cmp "${ws}/seed.resolved" "${ws}/swift/macos/Package.resolved" \
  || fail "seed was not copied"

# shellcheck disable=SC2016
expected_build='# Slice package for rules_swift_package_manager. Generated by
# `bazel run @rules_swift_package_manager//tools:init`; the cache tool
# rewrites inc.MODULE.bazel, Package.resolved and swift_deps_cache/.
package(default_visibility = ["//visibility:public"])'
[[ "$(cat "${ws}/swift/macos/BUILD.bazel")" == "${expected_build}" ]] \
  || fail "unexpected BUILD.bazel content"

assert_count 1 "swift/macos/.build" "${ws}/.bazelignore"
assert_count 1 "swift/macos/.build" "${ws}/.gitignore"
# Existing content without a trailing newline is preserved.
assert_count 1 "existing" "${ws}/.gitignore"

grep -qF 'include("//swift/macos:inc.MODULE.bazel")' <<<"${out}" \
  || fail "missing include line in output: ${out}"
grep -qF 'use_repo(swift_deps, "swift_package")' <<<"${out}" \
  || fail "missing use_repo line in output"
use_extension='swift_deps = use_extension('
use_extension+='"@rules_swift_package_manager//:extensions.bzl", "swift_deps")'
grep -qF "${use_extension}" <<<"${out}" \
  || fail "missing use_extension line in output"
# `bazel mod tidy` writes use_repo into the first file that uses the
# extension, so the include must come after the root use_extension.
use_extension_line="$(grep -nF "${use_extension}" <<<"${out}" | cut -d: -f1)"
include_line="$(grep -nF 'include("//swift/macos:' <<<"${out}" | cut -d: -f1)"
[[ ${use_extension_line} -lt ${include_line} ]] \
  || fail "use_extension must be printed before the include: ${out}"
grep -qF "Package.resolved" <<<"${out}" || fail "missing seed reminder"

# Second init in the same dir is refused.
if err="$("${init_sh}" --config @platforms//os:macos \
  --swift swift/Package.swift --dir swift/macos 2>&1)"; then
  fail "second init into the same dir should fail"
fi
grep -qF "inc.MODULE.bazel" <<<"${err}" || fail "refusal must name the file"

# Init into another dir: ignore files stay duplicate-free, and the
# use_extension lines are skipped once MODULE.bazel has swift_deps.
echo 'swift_deps = use_extension("//:e.bzl", "swift_deps")' \
  >>"${ws}/MODULE.bazel"
out="$("${init_sh}" --config @platforms//os:linux \
  --swift swift/Package.swift --dir swift/linux)"
assert_count 1 "swift/macos/.build" "${ws}/.bazelignore"
assert_count 1 "swift/linux/.build" "${ws}/.bazelignore"
assert_count 1 "swift/linux/.build" "${ws}/.gitignore"
grep -qF 'include("//swift/linux:inc.MODULE.bazel")' <<<"${out}" \
  || fail "missing include line for linux"
if grep -qF "use_repo(" <<<"${out}"; then
  fail "use_repo should not be printed when swift_deps exists"
fi

# Root-level Package.swift maps to //:Package.swift.
echo "// swift-tools-version: 5.9" >"${ws}/Package.swift"
"${init_sh}" --config //:cfg --swift Package.swift --dir slice >/dev/null
grep -qF 'swift = "//:Package.swift"' "${ws}/slice/inc.MODULE.bazel" \
  || fail "root-level swift label wrong"

# Error cases.
if "${init_sh}" --bogus >/dev/null 2>&1; then fail "unknown flag accepted"; fi
if "${init_sh}" --config //:c --swift nope/Package.swift --dir x \
  >/dev/null 2>&1; then fail "missing Package.swift accepted"; fi
if "${init_sh}" --config //:c --swift Package.swift --dir y \
  --seed missing >/dev/null 2>&1; then fail "missing seed accepted"; fi

# Runs init with the given arguments, expects it to fail, and checks that
# stderr contains the expected message.
assert_refused() {
  local expected="${1}"
  shift
  local err
  if err="$("${init_sh}" --config //:c "${@}" 2>&1)"; then
    fail "init ${*} should fail"
  fi
  grep -qF -- "${expected}" <<<"${err}" \
    || fail "init ${*}: expected '${expected}' in: ${err}"
}

# An existing BUILD or BUILD.bazel is never overwritten.
mkdir -p "${ws}/has_build" "${ws}/has_build_bazel"
echo "# client" >"${ws}/has_build/BUILD"
echo "# client" >"${ws}/has_build_bazel/BUILD.bazel"
assert_refused "${ws}/has_build/BUILD already exists" \
  --swift swift/Package.swift --dir has_build
assert_refused "${ws}/has_build_bazel/BUILD.bazel already exists" \
  --swift swift/Package.swift --dir has_build_bazel
[[ "$(cat "${ws}/has_build_bazel/BUILD.bazel")" == "# client" ]] \
  || fail "client BUILD.bazel was changed"

# The slice cannot be the directory that holds Package.swift.
assert_refused "--dir must differ from the directory of --swift (swift)" \
  --swift swift/Package.swift --dir swift
assert_refused "--dir must differ from the directory of --swift (swift)" \
  --swift ./swift/Package.swift --dir ./swift/
[[ ! -e "${ws}/swift/BUILD.bazel" ]] || fail "wrote swift/BUILD.bazel"

# Absolute paths, ".", ".." and empty components are rejected.
assert_refused "--dir must not be empty or the workspace root" \
  --swift swift/Package.swift --dir .
assert_refused "--dir must not be empty or the workspace root" \
  --swift swift/Package.swift --dir ./
assert_refused "--dir must be relative to the workspace root, got /abs" \
  --swift swift/Package.swift --dir /abs
assert_refused "--dir must not contain '.', '..' or empty components" \
  --swift swift/Package.swift --dir a/../b
assert_refused "--dir must not contain '.', '..' or empty components" \
  --swift swift/Package.swift --dir a/./b
assert_refused "--dir must not contain '.', '..' or empty components" \
  --swift swift/Package.swift --dir a//b
assert_refused "--swift must be relative to the workspace root" \
  --swift "${ws}/swift/Package.swift" --dir abs_swift
assert_refused "--swift must not contain '.', '..' or empty components" \
  --swift swift/../swift/Package.swift --dir dotdot_swift
assert_refused "--seed must be relative to the workspace root" \
  --swift swift/Package.swift --dir abs_seed --seed "${ws}/seed.resolved"
assert_refused "--seed must not contain '.', '..' or empty components" \
  --swift swift/Package.swift --dir dotdot_seed --seed x/../seed.resolved

# A single leading "./" is stripped from every path.
out="$("${init_sh}" --config //:c --swift ./swift/Package.swift \
  --dir ./dotted/ --seed ./seed.resolved)"
assert_file "${ws}/dotted/Package.resolved"
grep -qF 'include("//dotted:inc.MODULE.bazel")' <<<"${out}" \
  || fail "leading ./ not stripped from --dir: ${out}"
grep -qF 'swift = "//swift:Package.swift"' "${ws}/dotted/inc.MODULE.bazel" \
  || fail "leading ./ not stripped from --swift"
assert_count 1 "dotted/.build" "${ws}/.bazelignore"

echo "PASS"
