#!/usr/bin/env bash

set -o errexit -o nounset -o pipefail

# Bootstraps a slice package: BUILD.bazel, an empty inc.MODULE.bazel, ignore
# entries and an optional Package.resolved seed. Runs under `bazel run`.

usage() {
  cat >&2 <<USAGE
Usage: bazel run @rules_swift_package_manager//tools:init -- \\
  --swift <Package.swift> --dir <slice dir> --config <label> [--seed <file>]

Paths are relative to the workspace root.
USAGE
  exit 1
}

die() {
  echo >&2 "ERROR: ${*}"
  exit 1
}

swift=""
dir=""
config=""
seed=""
while [[ ${#} -gt 0 ]]; do
  case "${1}" in
    --swift | --dir | --config | --seed)
      [[ ${#} -ge 2 ]] || {
        echo >&2 "Missing value for ${1}"
        usage
      }
      case "${1}" in
        --swift) swift="${2}" ;;
        --dir) dir="${2}" ;;
        --config) config="${2}" ;;
        --seed) seed="${2}" ;;
      esac
      shift 2
      ;;
    *)
      echo >&2 "Unknown argument: ${1}"
      usage
      ;;
  esac
done
[[ -n ${swift} && -n ${dir} && -n ${config} ]] || usage

root="${BUILD_WORKSPACE_DIRECTORY:-}"
[[ -n ${root} ]] \
  || die "BUILD_WORKSPACE_DIRECTORY is not set; run this with bazel run."

[[ -f "${root}/${swift}" ]] || die "Package.swift not found: ${root}/${swift}"
if [[ -n ${seed} && ! -f "${root}/${seed}" ]]; then
  die "Seed not found: ${root}/${seed}"
fi

dir="${dir%/}"
inc_path="${root}/${dir}/inc.MODULE.bazel"
[[ ! -e ${inc_path} ]] \
  || die "${inc_path} already exists; refusing to overwrite."

# Label of Package.swift: //<dirname>:<basename>, or //:<basename> at the root.
swift_pkg="$(dirname "${swift}")"
[[ ${swift_pkg} != "." ]] || swift_pkg=""
swift_label="//${swift_pkg}:$(basename "${swift}")"
slice_pkg="//${dir}"

mkdir -p "${root}/${dir}"

cat >"${root}/${dir}/BUILD.bazel" <<'BUILD'
# Slice package for rules_swift_package_manager. Generated by
# `bazel run @rules_swift_package_manager//tools:init`; the cache tool
# rewrites inc.MODULE.bazel, Package.resolved and swift_deps_cache/.
package(default_visibility = ["//visibility:public"])
BUILD

# Keep in sync with the fixture inc.MODULE.bazel.empty.expected.
cat >"${inc_path}" <<INC
swift_deps = use_extension("@rules_swift_package_manager//:extensions.bzl", "swift_deps")
swift_deps.from_package(
    config = "${config}",
    swift = "${swift_label}",
    resolved = "${slice_pkg}:Package.resolved",
    dump_manifests = {},
    desc_manifests = {},
)
INC

# Appends a line to a file unless an identical line is present.
append_line_once() {
  local file="${1}" line="${2}"
  if [[ -f ${file} ]] && grep -qxF -- "${line}" "${file}"; then
    return 0
  fi
  if [[ -s ${file} && -n "$(tail -c 1 "${file}")" ]]; then
    echo >>"${file}"
  fi
  echo "${line}" >>"${file}"
}

append_line_once "${root}/.bazelignore" "${dir}/.build"
append_line_once "${root}/.gitignore" "${dir}/.build"

if [[ -n ${seed} ]]; then
  cp "${root}/${seed}" "${root}/${dir}/Package.resolved"
fi

echo "Created slice package ${slice_pkg}."
echo
echo "Add this to MODULE.bazel:"
echo
echo "include(\"${slice_pkg}:inc.MODULE.bazel\")"
if ! grep -qF '"swift_deps"' "${root}/MODULE.bazel" 2>/dev/null; then
  echo
  echo "Also add (the slice file uses it):"
  echo
  echo 'swift_deps = use_extension("@rules_swift_package_manager//:extensions.bzl", "swift_deps")'
  echo 'use_repo(swift_deps, "swift_package")'
fi
if [[ -n ${seed} ]]; then
  echo
  echo "Seed copied. Remove any Package.resolved beside Package.swift before"
  echo "running the cache tool."
fi
echo
echo "Next, run the cache tool under flags that select ${config}:"
echo
echo "  bazel run @swift_package//:resolve"
